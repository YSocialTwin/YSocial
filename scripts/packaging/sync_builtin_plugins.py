#!/usr/bin/env python3
"""Sync the built-in plugin list from the plugin registry (the single source of truth).

The plugins that ship with YSocial are described in ``builtin.json`` of
https://github.com/YSocialTwin/plugin-registry. YSocial packages a *generated* copy,
``y_web/src/external_runtime/builtin_plugins.json``, which records the registry commit
and a hash of the plugin list. Never edit the copy by hand: change ``builtin.json`` in
the registry, then run this script and release.

    # update the copy from a local checkout of the registry (needs a clean builtin.json)
    python scripts/packaging/sync_builtin_plugins.py --source plugin-registry
    # ... or from GitHub (a commit, tag or branch)
    python scripts/packaging/sync_builtin_plugins.py --ref 3dd57cc

    python scripts/packaging/sync_builtin_plugins.py --verify        # offline: copy not edited by hand
    python scripts/packaging/sync_builtin_plugins.py --check         # copy == registry at the recorded commit
    python scripts/packaging/sync_builtin_plugins.py --check-latest  # same plugin list as registry main (release gate;
                                                                     # a registry commit that does not change it passes)
"""

from __future__ import annotations

import argparse
import hashlib
import json
import subprocess
import sys
import urllib.error
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
TARGET = ROOT / "y_web" / "src" / "external_runtime" / "builtin_plugins.json"
REPO = "YSocialTwin/plugin-registry"
SOURCE_FILE = "builtin.json"
NOTE = (
    "Generated by scripts/packaging/sync_builtin_plugins.py from "
    f"{REPO}/{SOURCE_FILE}. Do not edit: change the registry and sync."
)


class SyncError(Exception):
    pass


def plugins_hash(plugins: list) -> str:
    canonical = json.dumps(plugins, sort_keys=True, separators=(",", ":"))
    return hashlib.sha256(canonical.encode("utf-8")).hexdigest()


def _get(url: str) -> bytes:
    request = urllib.request.Request(url, headers={"User-Agent": "ysocial-sync"})
    try:
        with urllib.request.urlopen(request, timeout=30) as response:
            return response.read()
    except (urllib.error.URLError, OSError) as exc:
        raise SyncError(f"cannot fetch {url}: {exc}") from exc


def from_checkout(path: Path) -> tuple[dict, str]:
    """``builtin.json`` of a local registry checkout, and the commit it is at."""
    source = path / SOURCE_FILE
    if not source.is_file():
        raise SyncError(f"{source} not found")

    def git(*args: str) -> str:
        result = subprocess.run(
            ["git", "-C", str(path), *args],
            capture_output=True,
            text=True,
            encoding="utf-8",
            errors="replace",
        )
        if result.returncode != 0:
            raise SyncError(f"git {' '.join(args)} failed: {result.stderr.strip()}")
        return result.stdout.strip()

    if git("status", "--porcelain", "--", SOURCE_FILE):
        raise SyncError(
            f"{SOURCE_FILE} has uncommitted changes in {path}: commit it first"
        )
    return json.loads(source.read_text(encoding="utf-8")), git("rev-parse", "HEAD")


def from_github(ref: str) -> tuple[dict, str]:
    """``builtin.json`` of the registry at *ref* (commit, tag or branch), and its commit."""
    info = json.loads(_get(f"https://api.github.com/repos/{REPO}/commits/{ref}"))
    commit = info["sha"]
    raw = _get(f"https://raw.githubusercontent.com/{REPO}/{commit}/{SOURCE_FILE}")
    return json.loads(raw.decode("utf-8")), commit


def check_source(payload: dict) -> None:
    if payload.get("schema_version") != 1 or not isinstance(
        payload.get("plugins"), list
    ):
        raise SyncError(f"unsupported {SOURCE_FILE} format")
    keys = [p.get("key") for p in payload["plugins"]]
    if len(keys) != len(set(keys)) or not all(keys):
        raise SyncError(f"{SOURCE_FILE}: missing or duplicate keys")


def render(payload: dict, commit: str) -> str:
    generated = {
        "note": NOTE,
        "source": f"{REPO}/{SOURCE_FILE}",
        "commit": commit,
        "sha256": plugins_hash(payload["plugins"]),
    }
    document = {
        "_generated": generated,
        "schema_version": payload["schema_version"],
        "plugins": payload["plugins"],
    }
    return json.dumps(document, indent=2, ensure_ascii=False) + "\n"


def current() -> dict:
    try:
        return json.loads(TARGET.read_text(encoding="utf-8"))
    except (OSError, ValueError) as exc:
        raise SyncError(f"cannot read {TARGET}: {exc}") from exc


def verify() -> list[str]:
    """Offline: the copy still matches the hash recorded when it was generated."""
    doc = current()
    generated = doc.get("_generated") or {}
    problems = []
    for field in ("source", "commit", "sha256"):
        if not generated.get(field):
            problems.append(f"_generated.{field} is missing (run the sync script)")
    if generated.get("sha256") and generated["sha256"] != plugins_hash(
        doc.get("plugins", [])
    ):
        problems.append(
            "the plugin list was edited by hand (hash differs): change "
            f"{SOURCE_FILE} in {REPO} and run the sync script"
        )
    return problems


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    group = parser.add_mutually_exclusive_group()
    group.add_argument("--source", type=Path, help="local checkout of the registry")
    group.add_argument("--ref", help="commit, tag or branch of the registry on GitHub")
    group.add_argument("--verify", action="store_true")
    group.add_argument("--check", action="store_true")
    group.add_argument("--check-latest", action="store_true")
    args = parser.parse_args(argv)
    try:
        if args.verify:
            problems = verify()
            for problem in problems:
                print(f"ERROR: {problem}")
            if not problems:
                print("OK: built-in plugin list matches its recorded hash")
            return 1 if problems else 0

        if args.check or args.check_latest:
            recorded = (current().get("_generated") or {}).get("commit")
            if args.check and not recorded:
                raise SyncError("no recorded commit: run the sync script")
            payload, commit = from_github("main" if args.check_latest else recorded)
            check_source(payload)
            if args.check_latest:
                # What matters for a release is the plugin list, not the registry commit:
                # a commit that only touches documentation (README, banner...) leaves the
                # list identical and must not fail the gate. Compare format and content.
                same = (
                    payload["schema_version"] == current().get("schema_version")
                    and plugins_hash(payload["plugins"])
                    == plugins_hash(current().get("plugins", []))
                )
                if same and not verify():
                    note = ""
                    if commit != recorded:
                        note = (
                            f" (registry main is at {commit[:7]}, the copy records "
                            f"{str(recorded)[:7]}: no change to the plugin list)"
                        )
                    print(f"OK: built-in plugin list is in sync with the registry main{note}")
                    return 0
            elif render(payload, commit) == TARGET.read_text(encoding="utf-8"):
                print(f"OK: builtin_plugins.json is in sync with {commit[:7]}")
                return 0
            what = (
                "the registry main" if args.check_latest else f"commit {recorded[:7]}"
            )
            print(
                f"ERROR: builtin_plugins.json differs from {what}; run "
                "'python scripts/packaging/sync_builtin_plugins.py --ref <commit>'"
            )
            return 1

        if args.source:
            payload, commit = from_checkout(args.source)
        else:
            payload, commit = from_github(args.ref or "main")
        check_source(payload)
        TARGET.write_text(render(payload, commit), encoding="utf-8")
        print(f"OK: {len(payload['plugins'])} plugins from {REPO}@{commit[:7]}")
        return 0
    except SyncError as exc:
        print(f"ERROR: {exc}")
        return 1


if __name__ == "__main__":
    sys.exit(main())
